"""
Утилиты для работы с текстом и генерации хэшей.

Содержит:
- make_hash: генерация SHA‑256 хэша от частей строки с предобработкой;
- normalize_text: нормализация пробельных символов в строке;
- matches_keywords: проверка наличия ключевых слов в тексте.

Все функции рассчитаны на работу с обычными строками; при передаче `None`
поведение описано в докстрингах отдельных функций.
"""
import hashlib
import re
from typing import Iterable


def make_hash(*parts: str) -> str:
    """
    Формирует SHA‑256 хэш от входных частей.

    Каждая переданная часть обрезается по краям (`strip()`), пустые части и
    `None` пропускаются. Части объединяются разделителем `||` и от этого
    результирующего строкового значения вычисляется шестнадцатеричный SHA‑256.

    Args:
        *parts (str): Произвольное количество строковых частей.

    Returns:
        str: Шестнадцатеричная строка SHA‑256 хэша.

    Примечания:
        - Если все части пустые или `None`, хэш будет вычислен от пустой строки.
    """
    s = "||".join([p.strip() for p in parts if p is not None])
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def normalize_text(s: str) -> str:
    """
    Нормализует строку, сводя последовательности пробельных символов к одному пробелу
    и убирая лидирующие/завершающие пробелы.

    Args:
        s (str): Входная строка. Если `None` или пустая строка, возвращается пустая строка.

    Returns:
        str: Нормализованная строка без лишних пробелов.
    """
    s = s or ""
    s = re.sub(r"\s+", " ", s).strip()
    return s


def matches_keywords(text: str, keywords: Iterable[str]) -> bool:
    """
    Проверяет, содержится ли хотя бы одно ключевое слово в тексте (регистронезависимо).

    Ключевые слова предварительно очищаются от пробелов и пустые значения игнорируются.
    Если список ключевых слов пуст или после очистки не остаётся элементов, функция
    возвращает `True` (нет ограничений по ключевым словам).

    Args:
        text (str): Текст для поиска. Если `None`, рассматривается как пустая строка.
        keywords (Iterable[str]): Итерабельный набор ключевых слов.

    Returns:
        bool: `True`, если найдена хотя бы одна совпадающая подстрока из ключевых слов,
              или если набор ключевых слов пуст; иначе `False`.
    """
    text_l = (text or "").lower()
    keys = [k.strip().lower() for k in keywords if k and k.strip()]
    if not keys:
        return True
    return any(k in text_l for k in keys)