"""Модуль для генерации текстов постов для Telegram-канала с использованием AI.

Предоставляет функциональность для создания коротких постов двух типов:
- Новостные посты на основе заголовка, источника и текста новости
- Посты-размышления на основе исходного текста с очисткой от рекламы и эзотерики
"""
from __future__ import annotations

from app.ai.ollama_client import OllamaClient

PROMPT_NEWS = """Ты редактор новостного Telegram-канала.
Сгенерируй короткий, яркий пост (до 600 символов) на русском языке по новости ниже.

Требования:
- 1–2 эмодзи в начале
- 2–4 коротких предложения
- в конце 1 call-to-action (вопрос читателю)
- без воды, без повторов
- без ссылок (если ссылка есть — добавь отдельной строкой в конце)

НОВОСТЬ:
Заголовок: {title}
Источник: {source}
Текст/сводка: {summary}
Ссылка: {url}
"""

PROMPT_THOUGHT = """Ты редактор Telegram-канала с размышлениями/лайфстайлом.
Сгенерируй короткий пост (до 600 символов) на русском языке по тексту ниже.

Требования:
- 1–2 эмодзи в начале
- 2–4 коротких предложения
- в конце 1 вопрос читателю
- убрать рекламу/прогрев/призывы записаться/“пиши + в комментариях”
- убрать эзотерику/астрологию/“вибрации” (заменить на нейтральные формулировки)
- без ссылок

ТЕКСТ:
{summary}
"""


def _trim(text: str, limit: int = 1200) -> str:
    """Обрезает текст до указанного лимита символов с сохранением целостности слов.

    Args:
        text: Исходный текст для обрезки
        limit: Максимальная длина текста в символах (по умолчанию 1200)

    Returns:
        Обрезанный текст с многоточием в конце, если превышен лимит,
        или исходный текст без изменений
    """
    text = (text or "").strip()
    if len(text) > limit:
        text = text[:limit].rsplit(" ", 1)[0] + "…"
    return text


async def generate_post_text(
    ollama: OllamaClient,
    title: str,
    summary: str,
    source: str,
    url: str | None,
    content_type: str = "news",
) -> str:
    """Генерирует текст поста для Telegram-канала с использованием AI.

    Единая точка генерации текста поста. В зависимости от типа контента
    использует разные промпты и правила форматирования.

    Args:
        ollama: Клиент для взаимодействия с Ollama AI
        title: Заголовок новости (используется только для типа "news")
        summary: Основной текст/сводка для генерации поста
        source: Источник новости (используется только для типа "news")
        url: Ссылка на источник (опционально, используется только для типа "news")
        content_type: Тип контента для генерации:
            - "news": новостной пост с заголовком, источником и ссылкой
            - "thought": пост-размышление с очисткой от рекламы и эзотерики

    Returns:
        Сгенерированный и обрезанный текст поста (до 1200 символов)

    Example:
        Для новостного поста:
            text = await generate_post_text(
                ollama=client,
                title="Новая технология",
                summary="Описание новости...",
                source="TechNews",
                url="https://example.com",
                content_type="news"
            )

        Для поста-размышления:
            text = await generate_post_text(
                ollama=client,
                title="",
                summary="Текст для переработки...",
                source="",
                url=None,
                content_type="thought"
            )
    """
    if content_type == "thought":
        prompt = PROMPT_THOUGHT.format(summary=summary)
    else:
        prompt = PROMPT_NEWS.format(
            title=title,
            summary=summary,
            source=source,
            url=url or "",
        )

    text = await ollama.generate(prompt)
    return _trim(text)